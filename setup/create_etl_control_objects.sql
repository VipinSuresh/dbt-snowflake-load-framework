-- Enterprise dbt Framework: Control Object Setup
--
-- Select the intended Snowflake database before executing.
-- The database must already exist.
-- Match the schema name to enterprise_control_schema
-- in dbt_project.yml.
--
-- Creates missing objects without replacing existing objects.
-- Existing tables are not altered or validated by this script.

CREATE SCHEMA IF NOT EXISTS ETL_CONTROL;

USE SCHEMA ETL_CONTROL;

CREATE TABLE IF NOT EXISTS ETL_RUN_CONTROL (
    ETL_NR NUMBER(38,0) NOT NULL,
    DBT_INVOCATION_ID VARCHAR(36) NOT NULL,
    EXECUTION_SOURCE VARCHAR(20) NOT NULL,
    JOB_NAME VARCHAR(255),
    DBT_TARGET_NAME VARCHAR(100),
    DBT_PROJECT_ID VARCHAR(40),
    DBT_ENVIRONMENT_ID VARCHAR(40),
    DBT_JOB_ID VARCHAR(40),
    DBT_CLOUD_RUN_ID VARCHAR(40),
    ORCHESTRATOR VARCHAR(100),
    ORCHESTRATOR_RUN_ID VARCHAR(255),
    EXECUTED_BY VARCHAR(255),
    DBT_COMMAND VARCHAR(1000),
    GIT_COMMIT_SHA VARCHAR(64),
    LOG_LOCATION VARCHAR(2000),
    BUSINESS_DATE DATE,
    RUN_STARTED_AT TIMESTAMP_NTZ(9) NOT NULL,
    RUN_ENDED_AT TIMESTAMP_NTZ(9),
    RUN_STATUS VARCHAR(40) NOT NULL,
    ERROR_MESSAGE VARCHAR(4000)
);

CREATE TABLE IF NOT EXISTS ETL_MODEL_STATS (
    MODEL_EXECUTION_ID VARCHAR(36) NOT NULL,
    ETL_NR NUMBER(38,0) NOT NULL,
    DBT_MODEL_ID VARCHAR(300) NOT NULL,
    TARGET_RELATION VARCHAR(500) NOT NULL,
    LOAD_TYPE VARCHAR(30) NOT NULL,
    SOURCE_ROW_COUNT NUMBER(38,0),
    TARGET_ROWS_BEFORE NUMBER(38,0),
    ROWS_INSERTED NUMBER(38,0),
    ROWS_UPDATED NUMBER(38,0),
    ROWS_DELETED NUMBER(38,0),
    TARGET_ROWS_AFTER NUMBER(38,0),
    LOAD_STATUS VARCHAR(40) NOT NULL,
    DQ_STATUS VARCHAR(20),
    STARTED_AT TIMESTAMP_NTZ(9) NOT NULL,
    FINISHED_AT TIMESTAMP_NTZ(9),
    ERROR_MESSAGE VARCHAR(4000)
);

CREATE TABLE IF NOT EXISTS ETL_DQ_RESULTS (
    DQ_RESULT_ID VARCHAR(36) NOT NULL,
    MODEL_EXECUTION_ID VARCHAR(36) NOT NULL,
    ETL_NR NUMBER(38,0) NOT NULL,
    CHECK_NAME VARCHAR(100) NOT NULL,
    CHECK_PHASE VARCHAR(20) NOT NULL,
    CHECK_STATUS VARCHAR(20) NOT NULL,
    OBSERVED_VALUE NUMBER(38,4),
    REFERENCE_VALUE NUMBER(38,4),
    THRESHOLD_PCT NUMBER(10,2),
    DETAILS VARIANT,
    CHECKED_AT TIMESTAMP_NTZ(9) NOT NULL
);

CREATE SEQUENCE IF NOT EXISTS ETL_NR_SEQ
    START WITH 1001
    INCREMENT BY 1
    NOORDER;

-- Framework-level serialization token for full-table replacement.
-- A singleton row is deliberately used so TRUNCATE_LOAD remains safe even when
-- the governed target is empty and has no row that can act as a lock anchor.
CREATE TABLE IF NOT EXISTS ETL_FRAMEWORK_LOCKS (
    LOCK_NAME VARCHAR(100) NOT NULL,
    LOCK_VERSION NUMBER(38,0) NOT NULL,
    LAST_ETL_NR NUMBER(38,0),
    LAST_MODEL_EXECUTION_ID VARCHAR(36),
    LAST_ACQUIRED_AT TIMESTAMP_NTZ(9)
);

MERGE INTO ETL_FRAMEWORK_LOCKS AS target
USING (
    SELECT 'TRUNCATE_LOAD_GLOBAL' AS LOCK_NAME
) AS source
ON target.LOCK_NAME = source.LOCK_NAME
WHEN NOT MATCHED THEN
    INSERT (
        LOCK_NAME,
        LOCK_VERSION,
        LAST_ETL_NR,
        LAST_MODEL_EXECUTION_ID,
        LAST_ACQUIRED_AT
    )
    VALUES (
        source.LOCK_NAME,
        0,
        NULL,
        NULL,
        NULL
    );
